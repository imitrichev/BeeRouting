/**
 * Утилиты для работы со временем в формате `HH:mm`.
 *
 * Модуль не зависит от дат и часовых поясов: работа ведётся только
 * с временем суток в 24-часовом формате.
 */

/**
 * Регулярное выражение для валидации времени в формате `HH:mm`
 * (00:00–23:59, ведущие нули обязательны).
 */
export const TIME_PATTERN = /^([01]\d|2[0-3]):[0-5]\d$/

/**
 * Проверяет, соответствует ли строка формату `HH:mm`.
 *
 * @param value Проверяемая строка.
 * @returns `true`, если строка — корректное время в формате `HH:mm`.
 */
export const isValidTime = (value: string): boolean => TIME_PATTERN.test(value)

/**
 * Переводит время в формате `HH:mm` в количество минут от начала суток.
 *
 * Предполагается, что `value` уже прошло валидацию (`isValidTime`);
 * поведение при неверном формате не определено.
 *
 * @param value Время в формате `HH:mm`.
 * @returns Количество минут от 00:00 (0–1439).
 */
export const timeToMinutes = (value: string): number => {
  const [h, m] = value.split(':').map(Number)
  return h! * 60 + m!
}
